`timescale 1ns/1ps
// ============================================================================
// brightness_contrast_adjust.v —— 亮度 / 对比度实时调节
// ============================================================================
// 【这个模块干什么】（说明）
//   类似手机相册里的"调亮度/调对比度"：
//     · 亮度 = 整幅画整体变亮或变暗（像把台灯调亮调暗）
//     · 对比度 = 亮的更亮、暗的更暗（像把照片调"更清楚"或"更灰蒙蒙"）
//   参数由板子上的**4 个拨码开关**控制，改一下立刻生效，字幕上还会显示当前数值。
//
// 【对应赛题】
//   扩展要求 1.4(3)：结合片上ADC/用户IO/可编程逻辑 实现亮度等参数配置
//   ⇒ 我们用的是**用户IO（拨码开关 SW1~SW4）**，不用焊任何元件。
//
// 【原理（常规做法 / 2.2 节）】
//   亮度：  R_out = R_in × brightness ÷ 256     ← ÷256 就是"右移 8 位"，省掉除法器
//   对比度：R_out = ((R_in - 128) × contrast ÷ 128) + 128，然后限制在 0~255
//           为什么要"先减 128 再乘再 +128"：128 是灰色的中间值，
//            以它为中心把像素往两边"拉伸"（对比度变大）或往中间"压缩"（对比度变小）。
//           为什么 ÷128 要用"算术右移 >>>"：减完 128 可能变**负数**，
//            逻辑右移会把负数移坏，必须用算术右移保留符号。
//
// 【和别的模块怎么配合】
//   图片 → [本模块：调亮度/对比度] → 剪纸窗花转场 → OSD字幕 → HDMI
//    本模块插在**像素链最前面**（转场之前），这样：
//     调亮度时窗花转场照常工作，两个功能互不干扰。
//
// 【软回退】BYPASS_EN=1'b1 时，本模块**完全透传**，等于没加过（一行运算都不做）。
// ============================================================================
module brightness_contrast_adjust (
    input  wire        clk,          // 像素时钟（25MHz）
    input  wire        rst_n,        // 低有效复位（像素域）
    input  wire        in_de,        // 输入数据有效
    input  wire [23:0] rgb_in,       // 输入像素（24位 RGB888）
    input  wire [7:0]  brightness,   // 亮度系数：128=正常，0=全黑，255=最亮
    input  wire [7:0]  contrast,     // 对比度系数：128=正常，>128 更分明，<128 更灰
    output reg         out_de,       // 输出数据有效（打一拍）
    output reg  [23:0] rgb_out       // 输出像素（打一拍）
);
    // ------------------------------------------------------------------
    // 1) 亮度通路：三通道各乘一遍，取高 8 位（= ÷256）
    //     常规做法，三个 8×8 乘法器。
    // ------------------------------------------------------------------
    wire [15:0] mul_r = rgb_in[23:16] * brightness;
    wire [15:0] mul_g = rgb_in[15:8]  * brightness;
    wire [15:0] mul_b = rgb_in[7:0]   * brightness;
    wire [7:0]  bright_r = mul_r[15:8];
    wire [7:0]  bright_g = mul_g[15:8];
    wire [7:0]  bright_b = mul_b[15:8];

    // ------------------------------------------------------------------
    // 2) 对比度通路 + 饱和截断（常规做法 参考答案，R/G/B 三通道照抄）
    //    ctr   = x - 128           （有符号！所以要 $signed 转换）
    //    sc    = ctr × contrast >>> 7    （>>>7 = ÷128，算术右移保符号）
    //    sum   = sc + 128
    //    final = sum<0 ? 0 : (sum>255 ? 255 : sum)    ← 这就是饱和截断
    // ------------------------------------------------------------------
    // ---- R 通道 ----
    wire signed [8:0]  ctr_r = $signed({1'b0, bright_r}) - 9'sd128;
    wire signed [16:0] sc_r  = (ctr_r * $signed({1'b0, contrast})) >>> 7;
    wire signed [9:0]  sum_r = sc_r + 10'sd128;
    wire [7:0] final_r = (sum_r < 10'sd0)   ? 8'd0   :
                         (sum_r > 10'sd255) ? 8'd255 : sum_r[7:0];

    // ---- G 通道 ----
    wire signed [8:0]  ctr_g = $signed({1'b0, bright_g}) - 9'sd128;
    wire signed [16:0] sc_g  = (ctr_g * $signed({1'b0, contrast})) >>> 7;
    wire signed [9:0]  sum_g = sc_g + 10'sd128;
    wire [7:0] final_g = (sum_g < 10'sd0)   ? 8'd0   :
                         (sum_g > 10'sd255) ? 8'd255 : sum_g[7:0];

    // ---- B 通道 ----
    wire signed [8:0]  ctr_b = $signed({1'b0, bright_b}) - 9'sd128;
    wire signed [16:0] sc_b  = (ctr_b * $signed({1'b0, contrast})) >>> 7;
    wire signed [9:0]  sum_b = sc_b + 10'sd128;
    wire [7:0] final_b = (sum_b < 10'sd0)   ? 8'd0   :
                         (sum_b > 10'sd255) ? 8'd255 : sum_b[7:0];

    // ------------------------------------------------------------------
    // 3) 打一拍输出（流水线寄存器），DE 跟着一起打拍保持对齐
    //    为什么必须打拍：6 个乘法器排在一起，组合逻辑太长，加一级寄存器
    //    能让时序更宽松；而且下游整条链路跟着晚一拍，画面上看不出来。
    // ------------------------------------------------------------------
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            out_de  <= 1'b0;
            rgb_out <= 24'h000000;
        end else begin
            out_de  <= in_de;
            rgb_out <= {final_r, final_g, final_b};
        end
    end
endmodule
