`timescale 1ns/1ps
// ============================================================================
// papercut_wipe.v  ——  【剪纸主题转场】"剪纸花边"擦除特效
// ============================================================================
// 【这个模块干什么】
//   把常规做法/2.3 节讲的 Wipe（揭示）做成**剪纸**的样子：
//   新图不是被一条**直边**擦出来，而是被一条**锯齿花边**擦出来，
//   像用剪刀沿着纸边剪开一样 —— 这就是"剪纸转场"。
//
// 【和常规的对应关系（一句一句对）】
//   常规做法
//       wire [9:0] wipe_boundary = ramp_out * (640 / FADE_FRAMES);
//       wire show_new_frame = wipe_active && (pixel_x < wipe_boundary);
//       assign final_rgb = wipe_active ? (show_new_frame ? new : old) : fade_rgb_after_alpha;
//
//   本模块 = 上面那三行的"剪纸版"：
//       boundary  = ramp_out * (640 / FADE_FRAMES)   ← **和常规设计一模一样，没改**
//       show_new  = pixel_x + 锯齿(pixel_y) < boundary   ← 唯一改动：边界加了个锯齿
//       final_rgb = show_new ? 新图 : 黑                ← "旧图"用黑代替（原因见下）
//
// 【为什么"旧图"用黑代替】（常规做法
//   常规做法，
//   自动轮播用 Wipe（因为切换是内部发起的，旧图已经没了）"。
//   我们的工程是**单读口保鲜柜 + 两块格子轮着用**（单口 SDRAM + 双缓冲），
//   换图的瞬间格子指针就翻了（sd_card_bmp.v 的 `disp_buf_idx <= pending_buf_idx`），
//   旧格马上被新图覆盖 ⇒ **物理上拿不到旧图**（常规做法。
//   ⇒ 所以"边界右边"显示**全黑**，也就是"刚从旧图淡出来的那个黑"。
//   ⇒ 视觉上就是：画面淡淡变黑 → 一道剪纸花边从左边剪开 → 新图从花边后露出来。
//
// 【为什么这样**绝对不会黑屏卡死**】（上次全黑的教训）
//   上次全黑是因为"边界判断卡住不动"⇒ 右边永远是黑。
//   这次：花边的推进量 wipe_ramp 由状态机的 ramp 驱动，**每帧必然 +1，
//   走满 FADE_FRAMES 帧就 return**，所以花边必然在 FADE_FRAMES 帧内扫完全屏，
//   最终整屏 100% 是新图。**数学上不可能停在半黑状态。**
//
// 【4 种方向】（常规做法
//   MODE=0：淡入淡出（本模块不参与，由顶层 Alpha 乘法负责）
//   MODE=1：剪纸花边**从左到右**（边界随 X 推进）
//   MODE=2：剪纸花边**从上到下**（边界随 Y 推进）
//   MODE=3：剪纸花边**从中心向外**（"开窗"，最有窗花味：距离中心 < 半径 ? 新 : 黑）
// ============================================================================
module papercut_wipe #(
    // 屏幕尺寸（默认 640×480，和赛题要求一致）
    parameter integer H_ACTIVE = 640,
    parameter integer V_ACTIVE = 480,
    // 花边锯齿的"齿宽"和"齿高"（必须是 2 的幂，这样只用移位、不用除法器）
    //   齿宽 16 像素、齿高 16 像素 —— 这个比例看着最像剪纸的锯齿边
    parameter integer TOOTH_W = 16,
    parameter integer TOOTH_H = 16,
    // 整个花边扫完需要多少帧（要和 video_fade_transition 的 FADE_FRAMES 一致）
    parameter integer FADE_FRAMES = 16      //  最后一项不能带逗号！
)(
    input  wire        pix_clk,      // 像素时钟（25MHz）
    input  wire        rst_n,        // 低有效复位（像素域）
    input  wire        wipe_active,  // Wipe 正在进行（来自 video_fade_transition）
    input  wire [4:0]  wipe_ramp,    // 边界推进计数器 0~FADE_FRAMES-1（来自 video_fade_transition）
    input  wire [1:0]  mode,         // 0=不做 1=左到右 2=上到下 3=中心向外
    input  wire [11:0] pixel_x,      // 当前像素 X（0~639）
    input  wire [11:0] pixel_y,      // 当前像素 Y（0~479）
    input  wire [23:0] new_rgb,      // 新图像素（= Alpha 乘法后的 faded_rgb）
    output wire [23:0] wipe_rgb,     // 剪纸擦除后的像素
    output wire        show_new      // 1=这一像素露新图（留作观察点/调试）
);
    // ------------------------------------------------------------------
    // 1) 边界推进量 —— 原始设计 boundary = ramp_out * (640 / FADE_FRAMES)
    //     但常规设计那个公式有个**缝**，我们这里必须补上：
    //      ramp 的最大值是 FADE_FRAMES-1 = 15（不是 16！），所以
    //        ramp × 40 = 15×40 = 600 < 640  ⇒ 最后一帧右边还剩 40 像素露不出来，
    //        屏幕上会永远留着一条 40 像素宽的黑边（模式2 同理剩 30 行）。
    //      ⇒ 所以推进量要按 "H / (FADE_FRAMES-1)" + 一点富余 来取：
    //         横向 640/15 = 42.67 ⇒ 取 44（15 帧盖满 660 > 640，稳）
    //         纵向 480/15 = 32    ⇒ 取 34（15 帧盖满 510 > 480，稳）
    //       这两个数都是**常数**，综合出来就是"移位+加法"，没有除法器。
    // ------------------------------------------------------------------
    wire [9:0] step_x = 10'd44;    // 每帧横向推进 44 像素（保证盖满 640）
    wire [9:0] step_y = 10'd34;    // 每帧纵向推进 34 像素（保证盖满 480）
    // 模式3的半径每帧长大 45：15 帧长到 15×45=675 > 最大菱形距离 560，
    //   ⇒ **整屏一定能开完**，绝不会停在半开状态（这是防"半黑卡住"的关键数字）。
    wire [9:0] step_r = 10'd45;

    // 横向边界：ramp × 40        （ramp 5 位，乘 40 最大 15×40=600，10 位够）
    wire [9:0] boundary_x = {5'd0, wipe_ramp} * step_x;
    // 纵向边界：ramp × 30
    wire [9:0] boundary_y = {5'd0, wipe_ramp} * step_y;

    // ------------------------------------------------------------------
    // 2) 剪纸花边：在"直边"上叠一个**三角波锯齿**
    //    齿宽 TOOTH_W=16：把坐标的低 4 位（0~15）拿出来，做成 0→15→0 的三角波
    //      低4位:  0  1  2 ...  7  8  9 ... 15
    //      锯齿 :  0  2  4 ... 14 16 14 ...  2      （先升后降 = 三角波）
    //    做法：t = 低4位；t 的 bit3 决定"上升还是下降"
    //          t < 8  → 锯齿 = t*2
    //          t >= 8 → 锯齿 = (15-t)*2
    //    这样每 16 像素起伏一次，最高点差 TOOTH_H(=16)。
    //     全是位运算和加法，**不产生乘法器/除法器**。
    // ------------------------------------------------------------------
    // 横向花边：锯齿跟着 Y 起伏（这样"从左到右"的边界是一条竖着的锯齿线）
    wire [3:0] ty = pixel_y[3:0];
    wire [4:0] zig_y = ty[3] ? ({1'b0, ~ty[2:0]} << 1) + 5'd2   // 下半齿：下降到 2
                             : ({1'b0, ty[2:0]}  << 1);          // 上半齿：上升到 14
    // 纵向花边：锯齿跟着 X 起伏（"从上到下"的边界是一条横着的锯齿线）
    wire [3:0] tx = pixel_x[3:0];
    wire [4:0] zig_x = tx[3] ? ({1'b0, ~tx[2:0]} << 1) + 5'd2
                             : ({1'b0, tx[2:0]}  << 1);

    // ------------------------------------------------------------------
    // 3) 三种模式的"是否在边界内"判断
    // ------------------------------------------------------------------
    // 模式1：从左到右。判断 (pixel_x + 花边锯齿) < boundary_x
    wire [11:0] cmp_x = {2'd0, boundary_x} ;
    wire        in_x  = ({1'b0, pixel_x[9:0]} + {7'd0, zig_y}) < cmp_x;

    // 模式2：从上到下。判断 (pixel_y + 花边锯齿) < boundary_y
    wire [11:0] cmp_y = {2'd0, boundary_y};
    wire        in_y  = ({1'b0, pixel_y[8:0]} + {7'd0, zig_x}) < cmp_y;

    // 模式3：从中心向外 —— 【剪纸"开窗"】窗花形（这是本工程的招牌效果）
    //   常规做法。
    //   真算欧氏距离要开平方，太贵。这里用**菱形距离**（|dx|+|dy|）：
    //     · 形状是菱形（比圆更像窗棂/窗花的外框）
    //     · 而且只要加减法，**不产生乘法器、不产生除法器**
//
    //    让它像"窗花"的关键：在半径上加一个**12 瓣的波浪**。
    //     波浪 = 每 60 度一个凸起，用 atan2 太贵；这里用一个便宜的近似：
    //       用 (|dx|, |dy|) 做"8 方向量化"，按方向给半径加一个固定的偏移量。
    //       8 个方向各给一个不同的偏移 = 窗口边缘出现 8 处起伏 ⇒ 像花瓣。
    //      全是比较和加法，没有三角函数。
    // ------------------------------------------------------------------
    wire [11:0] dx = (pixel_x > 12'd320) ? (pixel_x - 12'd320) : (12'd320 - pixel_x);
    wire [11:0] dy = (pixel_y > 12'd240) ? (pixel_y - 12'd240) : (12'd240 - pixel_y);
    wire [12:0] dist_man = {1'b0, dx} + {1'b0, dy};      // 菱形距离，最大 320+240=560

    // --- 4 瓣窗花：判断"这个方向是不是偏向 45 度对角线" ---
    //     偏对角线 ⇒ 半径多给 14 像素 ⇒ 四个角凸出去 = 4 个花瓣（方胜纹/窗棂的感觉）
    //     判据：在两条对角线附近（45°±26.6°）
    //       数学上 |dx - dy| 小就说明"离对角线近"
    //       用加法代替减法绝对值：min*2 > max 就说明两者接近
    wire [11:0] dx_min = (dx < dy) ? dx : dy;
    wire [11:0] dx_max = (dx < dy) ? dy : dx;
    wire [12:0] dmin2  = {1'b0, dx_min, 1'b0};        // 2*min
    wire        near_diag = (dmin2 > {1'b0, dx_max}); // 2*min > max  ⇒ 靠近对角线
    wire [12:0] petal = near_diag ? 13'd14 : 13'd0;

    // 半径：每帧长大 45（15 帧长到 675 > 560，全屏一定能开完），再叠花瓣和窗棂锯齿
    wire [12:0] radius = {3'd0, ({5'd0, wipe_ramp} * step_r)} + petal + {8'd0, zig_x};

    wire in_r = (dist_man < radius);

    // ============================================================================
    // ===== 【2026-10-01 诊断4】把"窗口判定结果 in_r"直接画出来 =====
    // ============================================================================
    // 【前面三诊断的结论（都是硬证据）】
    //   诊断1：彩带铺满整行      ⇒ pixel_x 正确（0~639）
    //   诊断2：de/vs 采样不合适   ⇒ 那两个信号相位不对，废弃不用
    //   诊断3：十字+绿框在正中央  ⇒ **pixel_x 和 pixel_y 都正确**，
    //                              而且"比较大小"这套写法也正确
    //   ⇒ 剩下唯一没验证过的，就是我自己算出来的 dist_man 和 radius。
//
    // 【这次直接把它俩画出来】不猜了，让芯片自己告诉我数算得对不对：
    //     in_r = 1（判定"在窗口内"）      → 画 **亮绿**
    //     in_r = 0（判定"在窗口外"）      → 画 **暗红**
    //   固定 ramp = WIPE_DEBUG_RAMP（诊断开关给的 8），所以窗口大小是固定的。
//
    // 【正常应该看到】正中央一块**亮绿色的菱形/四瓣花**，四周暗红。
    //     菱形是因为 dist_man（|dx|+|dy|）本身就是菱形。
    //     ramp=8 → radius=360，屏幕半宽 320、半高 240
    //     ⇒ 菱形会在**左右两边先被切掉**（320 < 360），上下还留着（240 < 360）
    //     ⇒ 所以形态应该是：一个**左右顶到边、上下留缺口**的大菱形。
//
    // 【怎么看】
    //   · 看到"中央一大块绿、四角红" ⇒ **in_r 是对的！** 那问题只在"什么时候
    //     允许它生效"（wipe_active 时机）⇒ 我改时机，不动数学。
    //   · 看到"整屏红" ⇒ in_r 恒 0 ⇒ radius 算错（很可能乘法溢出）
    //   · 看到"整屏绿" ⇒ in_r 恒 1 ⇒ dist_man 算错
    // ============================================================================
    wire [23:0] diag4_rgb = in_r ? 24'h00E000   // 判定"窗口内" = 亮绿
                                 : 24'h300000;  // 判定"窗口外" = 暗红

    // 诊断选择：0=正常  1=十字准星（已删）  2=in_r 可视化（绿色窗花/红色背景）
    //   【2026-10-01 已排查完，必须关掉！】
    //     我上一轮漏关了这个，导致烧出来是"绿窗花+红背景"的调试图而不是图片。
    //     交付/演示前这里**必须是 0**。
    localparam DIAG_SEL = 0;

    // ------------------------------------------------------------------
    // 4) 组装：show_new = 在边界内
    //     三重保险，保证"任何时候都不会只剩半屏黑"：
    //      保险① wipe_active=0（平时）→ 一律显示新图，画面完全正常。
    //      保险② ramp 走到最后一帧 → 强制显示新图。
    //             为什么必须加这一条：万一推进量算得不够、或者屏幕比参数大，
    //             最后一帧右边就会留一条黑边，而且**它会一直留在那儿**（上次全黑就是这么来的）。
    //             加上它 ⇒ 花边最后必然"收干净"，屏幕上不可能残留黑边。
    //      保险③ 顶层还有一道"出图有效就不许全零"的兜底（top 里那个 assign）。
    //    ⇒ 三条里任何一条单独成立，都不会黑屏。
    // ------------------------------------------------------------------
    wire last_frame = (wipe_ramp >= (FADE_FRAMES - 1));   // 最后一帧

    wire in_mode = (mode == 2'd1) ? in_x :
                   (mode == 2'd2) ? in_y :
                   (mode == 2'd3) ? in_r : 1'b0;

    // ---- 5) 最终输出：诊断图案优先，否则走正常的花边逻辑 ----
    //    DIAG_SEL=0 时诊断那一路**完全不存在**，等于没加过。
    wire [23:0] diag_rgb = (DIAG_SEL == 2) ? diag4_rgb : 24'd0;

    assign show_new = wipe_active ? (in_mode | last_frame) : 1'b1;
    assign wipe_rgb = (DIAG_SEL != 0) ? diag_rgb
                                      : (show_new ? new_rgb : 24'd0);   // 边界外 = 黑
endmodule
