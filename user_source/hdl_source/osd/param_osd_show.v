            7'd116: glyph_row = 8'b01100000;
            7'd117: glyph_row = 8'b01100000;
            7'd118: glyph_row = 8'b01100000;
            7'd119: glyph_row = 8'b00000000;
            // ---- 'T'（轮播周期 Time，字符号15）----
            7'd120: glyph_row = 8'b01111110;
            7'd121: glyph_row = 8'b00011000;
            7'd122: glyph_row = 8'b00011000;
            7'd123: glyph_row = 8'b00011000;
            7'd124: glyph_row = 8'b00011000;
            7'd125: glyph_row = 8'b00011000;
            7'd126: glyph_row = 8'b00011000;
            7'd127: glyph_row = 8'b00000000;
            default: glyph_row = 8'b00000000;
        endcase
    end

    // 取该字符第 gy 行里、第 gx 列的那一位（bit7 = 最左）
    wire glyph_pix = glyph_row[3'd7 - gx[2:0]];

    // ------------------------------------------------------------------
    // 【新功能】电影字幕效果：白字心 + 外圈黑描边
    // ------------------------------------------------------------------
    // 【为什么要描边】
    //   白色的字压在浅色/花哨的剪纸画面上会"糊成一片"看不清。
    //   在字的外面再包一圈**黑边**，就等效于给字镶了个"黑框"，
    //   不管背景是白是黑都能看清 —— 这就是电影字幕的做法。
    //
    // 【怎么算"外圈"】
    //   自己这一格没字（glyph_pix=0），但**上下左右相邻**的格里有字
    //   ⇒ 说明我正好在某个字的边上 ⇒ 画黑边。
    //   例：字的形状像一块饼干，描边就是饼干边缘那圈糖霜。
    //
    // 【怎么拿到"邻居"有没有字】
    //   同一行里左/右邻居：把 glyph_row **整体左移/右移一位**，就得到了邻居的像素。
    //       glyph_row 的 bit7 是最左边，所以：
    //         "左边邻居有字" = glyph_row << 1 的对应位
    //         "右边邻居有字" = glyph_row >> 1 的对应位
    //   上下邻居需要**另一行**的字模，这里用"上一行/下一行"再做一次查表。
    //    为了省资源、也为了不引入打拍延迟（会错位），
    //     这里只做**左/右 + 上** 三个方向（下方向在下一行字自己会补上）。
    // ------------------------------------------------------------------
    // 左邻居 / 右邻居（同一行内移位即可）
    wire [7:0] glyph_row_l = {glyph_row[6:0], 1'b0};   // 左边邻居：把字模往右挪一格看
    wire [7:0] glyph_row_r = {1'b0, glyph_row[7:1]};   // 右边邻居
    wire glyph_pix_l = glyph_row_l[3'd7 - gx[2:0]];
    wire glyph_pix_r = glyph_row_r[3'd7 - gx[2:0]];

    // 上邻居：查"同一字符的上一行"（gy-1），在**组合逻辑**里再查一次，不打拍
    wire [2:0] gy_up   = gy - 3'd1;
    wire [6:0] addr_up = {ch_sel, gy_up};
    reg  [7:0] glyph_row_up;
    always @* begin
        case (addr_up)
            // ---- 'B' 上一行（字符号10）----
            7'd80 : glyph_row_up = 8'b01111100;
            7'd81 : glyph_row_up = 8'b01100110;
            7'd82 : glyph_row_up = 8'b01100110;
            7'd83 : glyph_row_up = 8'b01111100;
            7'd84 : glyph_row_up = 8'b01100110;
            7'd85 : glyph_row_up = 8'b01100110;
            7'd86 : glyph_row_up = 8'b01111100;
            // ---- 'P' 上一行（字符号14）----
            7'd112: glyph_row_up = 8'b01111100;
            7'd113: glyph_row_up = 8'b01100110;
            7'd114: glyph_row_up = 8'b01100110;
            7'd115: glyph_row_up = 8'b01111100;
            7'd116: glyph_row_up = 8'b01100000;
            7'd117: glyph_row_up = 8'b01100000;
            7'd118: glyph_row_up = 8'b01100000;
            // ---- 'T' 上一行（字符号15）----
            7'd120: glyph_row_up = 8'b01111110;
            7'd121: glyph_row_up = 8'b00011000;
            7'd122: glyph_row_up = 8'b00011000;
            7'd123: glyph_row_up = 8'b00011000;
            7'd124: glyph_row_up = 8'b00011000;
            7'd125: glyph_row_up = 8'b00011000;
            7'd126: glyph_row_up = 8'b00011000;
            default: glyph_row_up = 8'b00000000;
        endcase
    end
    wire glyph_pix_up = glyph_row_up[3'd7 - gx[2:0]];

    // "我这一格没字，但邻居有字" ⇒ 我是描边
    //    gy=0 时屏蔽上邻居（第一行上面没东西，屏蔽掉防止乱算）
    wire glyph_halo = !glyph_pix && (
                        glyph_pix_l || glyph_pix_r ||
                        ((gy != 3'd0) && glyph_pix_up) );

    // ------------------------------------------------------------------
    // 【新功能】输出：电影字幕风格（白字 + 黑边），面板不再画实心底
    // ------------------------------------------------------------------
    //   字心   → 纯白  24'hFFFFFF
    //   描边   → 纯黑  24'h000000
    //   其它   → **完全透明**（hit=0，画面原样透出来，不再有深色底块）
    //   ⇒ 视觉上就是"白色电影字幕，字外面包一圈黑边"，压在剪纸画面上，干净。
    // ------------------------------------------------------------------
    wire panel_pixel = glyph_pix || glyph_halo;

    // [fix] 加上 col_ok / row_ok：列号超过 3 或行号超过 2 的多余格子一律不画
    assign hit       = SHOW_ENABLE && in_char_x && in_char_y && col_ok && row_ok
                       && panel_pixel && display_on;
    assign panel_rgb = glyph_pix ? 24'hFFFFFF   // 字心：纯白
                                 : 24'h000000;  // 描边：纯黑
endmodule
