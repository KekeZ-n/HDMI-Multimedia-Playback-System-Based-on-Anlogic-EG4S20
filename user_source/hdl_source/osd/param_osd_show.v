`timescale 1ns/1ps
// ============================================================================
// param_osd_show.v —— 【扩展项(4) 下半部分】把"当前参数值"显示在画面上
// ============================================================================
// 【赛题原文】扩展要求(4)："利用板载开关或按键调节显示参数（如亮度、对比度等），
//             并尝试**在画面上呈现参数变化信息**。"
//   ⇒ 上一轮我们做了"拨码能调亮度"，但**画面上看不到数值**。
//     这个模块补的就是后半句：**把参数值实时显示出来**。
//
// 【为什么单独写一个模块，而不动原来的汉字字幕】
//   原来的 osd_cn_text 是"汉字点阵"路线，改它要动字库、动调度，风险大。
//   这里做的是一块**独立的"数字仪表"**：只画数字（0-9）和几个固定字，
//   用**8×8 点阵**（一个小 ROM），和汉字系统**互不干扰**，可以随时旁路。
//
// 【显示什么】屏幕左下角一块小面板，三行内容：
//     亮度 128
//     对比 128
//     曲目 1
//   （每行 6 个字符位：4 个汉字位用简化符号代替 + 3 位数字）
//    为了省资源，这里**不画汉字**，只用"B=亮度 / C=对比度 / N=曲目"的字母简写，
//     加数字。评委看得懂，而且资源几乎为零。
//
// 【怎么画字】用一张 8×8 点阵小字库，只有 13 个字符：
//     0-9 十个数字 + B + C + N + 空格
//   ⇒ 13 × 8 字节 = 104 字节，非常小。
//
// 【软回退】SHOW_ENABLE=1'b0 → 完全不贴，像素原样透传，等于没加过。
// ============================================================================
module param_osd_show #(
    parameter integer PANEL_X = 12,     // 面板左上角 X（像素）
    parameter integer PANEL_Y = 300,    // 面板左上角 Y（像素）
    parameter         SHOW_ENABLE = 1'b1
)(
    input  wire        clk,
    input  wire [11:0] pixel_x,      // 当前像素 X（0~639）
    input  wire [11:0] pixel_y,      // 当前像素 Y（0~479）
    input  wire [7:0]  brightness,   // 当前亮度值（0~255）
    input  wire [7:0]  contrast,     // 当前对比度值（0~255）
    input  wire [3:0]  tune_no,      // 当前曲目号（1~4）
    input  wire [3:0]  page_no,      // 【新】当前页码（1~4）
    input  wire [5:0]  period_s,     // 【新】轮播周期（秒：2/3/5/8）
    input  wire        display_on,   // 1=有图可显示（=display_valid）
    output wire        hit,          // 1=这个像素属于面板（要贴色）
    output wire [23:0] panel_rgb     // 面板像素颜色
);
    // ------------------------------------------------------------------
    // 面板尺寸：12 字符宽 × 3 行
    //   【重要修坑】字格必须取**2 的幂**（这里取 8），这样"第几列/第几行"
    //     就能直接用**移位**算出来。
    //     上一版字格取 9（8像素字+1间距），结果要写 `rel_x / 9`，
    //     虽然除数是常数、TD 能优化，但**对信号做 / 和 % 有综合出除法器的风险**
    //     （我们的资源很宽裕，但没必要冒这个险）。
    //     ⇒ 字格改成 8：字还是 8×8，**字符之间不留缝**，靠底色把字分开，
    //       依旧清楚，而且全部是移位，**绝对不会有除法器**。
    // ------------------------------------------------------------------
    localparam integer PANEL_W = 4 * 8 + 4;   // 4 个字符宽 = 32 像素（+4 是右边留白）
    localparam integer PANEL_H = 3 * 8 + 3;   // 3 行 = 24 像素（+3 是下边留白）

    // 面板边框：原设计往外扩 2 像素画深色底框
    //   【本次改动】面板改成"电影字幕"风格后**不再画实心底**，只画"白字+黑边"，
    //     所以下面这几个 in_panel_* 判定已经用不到了，保留注释说明来龙去脉。
    //     （删掉定义是为了省资源，也避免"定义了没用"产生综合警告）
    // wire in_panel_x = (pixel_x >= PANEL_X - 2) && (pixel_x < PANEL_X + PANEL_W + 2);
    // wire in_panel_y = (pixel_y >= PANEL_Y - 2) && (pixel_y < PANEL_Y + PANEL_H + 2);
    // wire in_panel   = in_panel_x && in_panel_y && display_on;

    // 面板内部的相对坐标
    // 【修复：为什么看起来是 4 行】
    //   原来 rel_y 从 PANEL_Y-2 开始算（把外扩的 2 像素边框也算进了"字符区"）：
    //       rel_y = pixel_y - (PANEL_Y - 2)
    //   但字符格是 8 像素，边框那 2 像素会被算成"第 0 行的前 2 行"，
    //   整个内容**下移 2 像素**，最后一行下面再漏出 3 像素 ⇒ 看着像多了一行空的。
    //   ⇒ 现在把"字符区"和"边框"彻底分开：
    //       字符区：从 PANEL_Y 开始，严格 3 行 × 8 像素
    //       边框  ：pad_top/pad_left 只有 1 像素，且**不参与字符定位**
    // ==================================================================
    // 字符区起点（严格对齐到 PANEL_X / PANEL_Y）
    // 【修复："还有残留"是什么】
    //   面板常量里带了"留白"：
    //       PANEL_W = 4*8 + 4 = 36   ← 后面 +4 是留白
    //       PANEL_H = 3*8 + 3 = 27   ← 后面 +3 是留白
    //   但判定"在不在面板里"用的是 PANEL_W/PANEL_H，
    //   ⇒ **那 4 像素留白被当成第 5 列**、**3 像素留白被当成第 4 行**，
    //     而 case 的 default 分支会往这些"多出来的格子"里画字！
    //   ⇒ 屏幕上就看到面板右边/下边**多出一小块字**（就是你说的"残留"）。
    //
    //   【正确做法】画字的范围**只算真正的字格**：4 列 × 3 行，留白那几像素不画。
    // ==================================================================
    // 【本次改动：面板放大一倍】
    //   【为什么】原来每个字符只有 8×8 像素，在大屏幕和投影上太小，
    //           拍摄时几乎看不清 B/P/T 的数字。要求"大一倍，但不能遮住剪纸图"。
    //   【怎么做的（最省资源的方式）】
    //     不重画字库（字库还是 8×8），只把**每个点放大成 2×2 方块**：
    //       字格 8 → 16 像素，整个面板 32×24 → 64×48 像素
    //       屏幕 640×480 上只占 64/640 = 10% 宽、48/480 = 10% 高，
    //       放在右上角**完全不遮主体**。
    //   【原理】把"字符内坐标"右移 1 位再查字模：
    //       gy = rel_y[3:1]   ← 原来取 [2:0]
    //       gx = rel_x[3:1]   ← 原来取 [2:0]
    //     ⇒ 屏幕上的 2 个像素对应字模的 1 个点，天然就是 2 倍放大，零额外逻辑。
    //    想调回 1 倍：把 SCALE_SHIFT 改成 0；想 3 倍：改成 2（字格 24）
    // ==================================================================
    localparam integer SCALE_SHIFT = 1;                  // 1 = 放大 2 倍（2^1）
    localparam integer CELL        = 8 << SCALE_SHIFT;   // 字格像素 = 16
    localparam integer TEXT_W      = 4 * CELL;           // 字符区宽 = 64
    localparam integer TEXT_H      = 3 * CELL;           // 字符区高 = 48

    wire in_char_x = (pixel_x >= PANEL_X) && (pixel_x < PANEL_X + TEXT_W);
    wire in_char_y = (pixel_y >= PANEL_Y) && (pixel_y < PANEL_Y + TEXT_H);

    // 相对"字符区起点"的坐标（这样第 0 行就是第 0 行，不会错位）
    wire [11:0] rel_x = pixel_x - PANEL_X;
    wire [11:0] rel_y = pixel_y - PANEL_Y;

    //  全部用移位：col = rel_x>>4，row = rel_y>>4，字内坐标 = 低 4 位再右移 1 位
    wire [7:0]  col   = rel_x[10:4];              // 第几列字符（0~3）
    wire [7:0]  row   = rel_y[10:4];              // 第几行字符（0~2）
    wire [2:0]  gy    = rel_y[3:1];               // 字符内第几行（0~7），高 3 位
    wire [2:0]  gx    = rel_x[3:1];               // 字符内第几列（0~7），高 3 位

    // 列号 / 行号超范围 ⇒ 不画（双保险，防止 default 分支乱画）
    wire col_ok = (col <= 8'd3);
    wire row_ok = (row <= 8'd2);

    // 面板范围内才画字（8×8 全部是字，没有间距了）
    // 【已不用】in_glyph：原来恒 1，现在改成按 in_char_x/in_char_y 判定
    // ------------------------------------------------------------------
    // 三行显示内容（【已改成】只用 B / P / T 三个参数，不多不少）：
    //   第0行： B + 三位亮度十进制      → 例 "B 128"
    //   第1行： P + 一位页码            → 例 "P 3"
    //   第2行： T + 一位轮播周期（秒）   → 例 "T 2"
    //   每行只占前 4 列，其余列一律留空（col_ok/row_ok 已经把它们挡掉了）
    // ------------------------------------------------------------------
    // 【重要】十进制拆位**绝不能用 / 和 %**
    //   在 Verilog 里对"信号"做 / 或 % 会综合出**除法器**，我们踩过这个坑。
    //   这里改用**逐次比较减法**（纯比较+减法，没有除法器）：
    //     百位 = 值 >= 100 ? 值 >= 200 ? 2 : 1 : 0
    //     余数 = 值 - 百位×100
    //     十位 = 余数 >= 10 ? 余数>=20?2:余数>=30?3:...:0   ← 展开成一张小表
    //     个位 = 余数 - 十位×10
    //   因为亮度/对比度只可能有 0/128/160/192/224 这几个值（4 档），
    //   十位最多到 2，所以表很短。
    // ------------------------------------------------------------------
    function [3:0] dec100;   // 百位
        input [7:0] v;
        begin
            if      (v >= 8'd200) dec100 = 4'd2;
            else if (v >= 8'd100) dec100 = 4'd1;
            else                  dec100 = 4'd0;
        end
    endfunction

    function [3:0] dec10;    // 十位
        input [7:0] v;       // 传入的是"去掉百位后的余数"（0~99）
        begin
            if      (v >= 8'd90) dec10 = 4'd9;
            else if (v >= 8'd80) dec10 = 4'd8;
            else if (v >= 8'd70) dec10 = 4'd7;
            else if (v >= 8'd60) dec10 = 4'd6;
            else if (v >= 8'd50) dec10 = 4'd5;
            else if (v >= 8'd40) dec10 = 4'd4;
            else if (v >= 8'd30) dec10 = 4'd3;
            else if (v >= 8'd20) dec10 = 4'd2;
            else if (v >= 8'd10) dec10 = 4'd1;
            else                 dec10 = 4'd0;
        end
    endfunction

    // 亮度拆位
    wire [3:0] b100 = dec100(brightness);
    wire [7:0] b_rem = brightness - ({4'd0, b100} * 8'd100);   // ×100 是常数乘法→移位加法
    wire [3:0] b010 = dec10(b_rem);
    wire [3:0] b001 = b_rem - ({4'd0, b010} * 8'd10);          // ×10 也是常数乘法

    // 对比度拆位： 已删除（面板不再显示对比度，省下这些逻辑）
    //   对比度仍然可以用 SW3/SW4 调节，只是不显示数值。
    //   tone_no 也不再使用（面板改显示页码和周期）。

    // 轮播周期拆位：周期只有 2/3/5/8 这 4 种可能，**用查表，绝不用除法器**
    //   十位：8→0, 5→0, 3→0, 2→0    ⇒ 全是 0（都是个位数）
    //   个位：2/3/5/8 直接就是数值本身
    //   ⇒ 周期是 "秒数"，最大 8，所以**一个字符就够**，不需要十位。
    //     但为了排版和"T 2"看着对称，第 2 列固定显示 0（即 "T 08" 的样子不划算），
    //     这里改成直接显示单个数字，第 2/3 列留空。
    wire [3:0] period_digit = {2'b00, period_s[3:0]};   // 2/3/5/8 → 本身就是个位数字

    // 按 (行, 列) 选出该位置要画的"字符编号"
    //   字符编号：0~9 = 数字 0~9；10='B'；11='C'；12='N'；13=空格；14='P'；15='T'
    //   【本次改动】面板三行改成：
    //       行0：B 128   ← 亮度 Brightness（3 位数字）
    //       行1：P 3     ← 页码 Page（第几张图，1 位数字）
    //       行2：T 2     ← 轮播周期 Time（秒，1 位数字）
    //     原来是 亮度/对比度/曲目号，按需求换成 亮度/页码/周期。
    //     （对比度仍可用 SW3/SW4 调，只是不显示；曲目号用不上了）
    //    仍然**不用嵌套 case**：先按列选数字，再按行给前缀字符。
    reg [3:0] num_sel;       // 该列对应的数字（0~9）
    always @* begin
        case (col[3:0])
            4'd1:    num_sel = (row == 4'd1) ? page_no      :
                               (row == 4'd2) ? period_digit : b100;
            4'd2:    num_sel = (row == 4'd1) ? 4'd13        :
                               (row == 4'd2) ? 4'd13        : b010;
            4'd3:    num_sel = (row == 4'd1) ? 4'd13        :
                               (row == 4'd2) ? 4'd13        : b001;
            default: num_sel = 4'd13;   // 空格
        endcase
    end

    reg [3:0] ch_sel;
    always @* begin
        case (row[3:0])
            4'd0: ch_sel = (col == 4'd0) ? 4'd10 :   // 'B' 亮度
                           (col <= 4'd3)  ? num_sel : 4'd13;
            4'd1: ch_sel = (col == 4'd0) ? 4'd14 :   // 'P' 页码
                           (col == 4'd1)  ? num_sel : 4'd13;
            default: ch_sel = (col == 4'd0) ? 4'd15 : // 'T' 轮播周期
                              (col == 4'd1)  ? num_sel : 4'd13;
        endcase
    end

    // ------------------------------------------------------------------
    // 8×8 点阵小字库：只存 0~9 + B + C + N + 空格，共 14 个字符
    //   每个字符 8 行，每行 8 位（bit7 = 最左边那个像素）
    //   【重要】必须写成**扁平的单层 case**：
    //     之前试过"case(字符) 里再套 case(行号)"，那叫**嵌套 case**，
    //     TD 对嵌套结构支持不稳（我们踩过"嵌套 generate"的同类坑），
    //     ⇒ 改成"用 {字符号, 行号} 拼成一个 7 位索引，只用一个 case 查"，
    //        结构是**一层**的，TD 一定认，而且综合结果一样。
    // ------------------------------------------------------------------
    wire [6:0] glyph_addr = {ch_sel, gy[2:0]};   // 高位=字符号(4位)，低位=行号(3位)

    reg [7:0] glyph_row;
    always @* begin
        case (glyph_addr)
            // ---- 数字 0（字符号0）----
            7'd0  : glyph_row = 8'b00111100;   // 行0
            7'd1  : glyph_row = 8'b01100110;
            7'd2  : glyph_row = 8'b01101110;
            7'd3  : glyph_row = 8'b01110110;
            7'd4  : glyph_row = 8'b01100110;
            7'd5  : glyph_row = 8'b01100110;
            7'd6  : glyph_row = 8'b00111100;
            7'd7  : glyph_row = 8'b00000000;
            // ---- 数字 1（字符号1）----
            7'd8  : glyph_row = 8'b00011000;
            7'd9  : glyph_row = 8'b00111000;
            7'd10 : glyph_row = 8'b00011000;
            7'd11 : glyph_row = 8'b00011000;
            7'd12 : glyph_row = 8'b00011000;
            7'd13 : glyph_row = 8'b00011000;
            7'd14 : glyph_row = 8'b01111110;
            7'd15 : glyph_row = 8'b00000000;
            // ---- 数字 2（字符号2）----
            7'd16 : glyph_row = 8'b00111100;
            7'd17 : glyph_row = 8'b01100110;
            7'd18 : glyph_row = 8'b00000110;
            7'd19 : glyph_row = 8'b00001100;
            7'd20 : glyph_row = 8'b00110000;
            7'd21 : glyph_row = 8'b01100000;
            7'd22 : glyph_row = 8'b01111110;
            7'd23 : glyph_row = 8'b00000000;
            // ---- 数字 3（字符号3）----
            7'd24 : glyph_row = 8'b00111100;
            7'd25 : glyph_row = 8'b01100110;
            7'd26 : glyph_row = 8'b00000110;
            7'd27 : glyph_row = 8'b00011100;
            7'd28 : glyph_row = 8'b00000110;
            7'd29 : glyph_row = 8'b01100110;
            7'd30 : glyph_row = 8'b00111100;
            7'd31 : glyph_row = 8'b00000000;
            // ---- 数字 4（字符号4）----
            7'd32 : glyph_row = 8'b00001100;
            7'd33 : glyph_row = 8'b00011100;
            7'd34 : glyph_row = 8'b00111100;
            7'd35 : glyph_row = 8'b01101100;
            7'd36 : glyph_row = 8'b01111110;
            7'd37 : glyph_row = 8'b00001100;
            7'd38 : glyph_row = 8'b00001100;
            7'd39 : glyph_row = 8'b00000000;
            // ---- 数字 5（字符号5）----
            7'd40 : glyph_row = 8'b01111110;
            7'd41 : glyph_row = 8'b01100000;
            7'd42 : glyph_row = 8'b01111100;
            7'd43 : glyph_row = 8'b00000110;
